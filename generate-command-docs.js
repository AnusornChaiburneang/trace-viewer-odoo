#!/usr/bin/env node
const fs = require('fs');
const path = require('path');
const commands = require('./commands.json');
const output = '# Trace Kit commands\n\nGenerated from `commands.json`. Do not edit this file directly.\n\n' +
  commands.map(c => `- \`${c.usage}\` — ${c.description}`).join('\n') + '\n';
const filename = path.join(__dirname,'COMMANDS.md');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(filename) || fs.readFileSync(filename,'utf8') !== output) {
    console.error('COMMANDS.md is stale; run node generate-command-docs.js');process.exitCode=1;
  }
} else fs.writeFileSync(filename,output);
