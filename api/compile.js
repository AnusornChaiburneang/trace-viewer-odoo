// Turn one transaction of a validated run into a flow file for one language.
// The flow uses only P2 commands; credentials stay {{LOGIN}}/{{PASSWORD}} and
// are supplied through TRACE_VAR_* at spawn time, so flow files hold no secrets.
const { textFor } = require('./validate');

// The flow tokenizer has no escape for a single quote inside a quoted token.
// Captions are prose, so a typographic apostrophe is the right glyph anyway.
const q = (s) => String(s).replace(/'/g, '’');

function compileFlow(run, tx, lang) {
  const o = run.options;
  const lines = [
    `# generated by trace-kit API — run ${run.id}, transaction ${tx.id}, ${lang}`,
    'strict on',
    `timeout ${o.timeout_ms}`,
    `mode ${o.mode}`,
    'login {{LOGIN}} {{PASSWORD}}',
    `lang ${lang}`,
  ];
  tx.steps.forEach((st, i) => {
    const title = textFor(st.title, lang);
    const desc = textFor(st.description, lang);
    lines.push('', `step '${q(title)}'${desc ? ` '${q(desc)}'` : ''}`);
    for (const c of st.commands) lines.push(c.trim());
    for (const e of st.expect) lines.push(`expect ${e.trim()}`);
    if (st.highlight) {
      const cap = textFor(st.highlight.caption, lang);
      lines.push(`mark '${st.highlight.selector}'${cap ? ` ${q(cap)}` : ''}`);
    }
    // Transaction-level captures run at the end of the last step, on its screen.
    if (i === tx.steps.length - 1) {
      for (const [name, spec] of Object.entries(tx.capture)) lines.push(`capture ${name} ${spec}`);
    }
  });
  lines.push('done', '');
  return lines.join('\n');
}

// Separate tiny flow used after the batch to put the user's language back.
function restoreFlow(lang) {
  return ['# restore the user language after the batch', 'login {{LOGIN}} {{PASSWORD}}', `lang ${lang}`, 'done', ''].join('\n');
}

module.exports = { compileFlow, restoreFlow };
